#!/usr/bin/env python3
"""Build the Chrome extension folder, its ZIP and the Android app's assets."""
import argparse
import json
from pathlib import Path
import shutil
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
# Card info overlay and rarity foil sources, in load order; build output bundles them with
# the stylesheets.
OVERLAY_DIR = ROOT / "extension/overlay"
OVERLAY_SCRIPTS = ("features.js", "keywords.js", "icons.js", "layout.js", "resources.js", "handcount.js", "holo.js", "foil.js", "overlay.js")
OVERLAY_STYLES = ("overlay.css", "holo.css")
# The Chrome extension's settings menu and its page bridge; the Android app has no menu, so
# none of it is packaged there. The menu shares the overlay's list of additions.
SETTINGS_DIR = ROOT / "extension/settings"
SETTINGS_FILES = ("popup.html", "popup.css", "popup.js", "bridge.js")
OUTPUTS = ("extension", "android-assets", "android-res")


def overlay_bundle():
    """One script for Chrome and the Android WebView: the stylesheet text, then the runtime.

    The site's CSP blocks injected <style> elements, so the runtime adopts the CSS as a
    constructed stylesheet instead.
    """
    css = "\n".join((OVERLAY_DIR / name).read_text(encoding="utf-8") for name in OVERLAY_STYLES)
    parts = ["// Generated by tools/build.py from extension/overlay/. Do not edit.",
             f"window.__CBL_OVERLAY_CSS = {json.dumps(css)};"]
    parts += [(OVERLAY_DIR / name).read_text(encoding="utf-8") for name in OVERLAY_SCRIPTS]
    return "\n".join(parts) + "\n"


def package(output):
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    marker = output / ".cardbattlelab-generated"
    if not marker.is_file() and any((output / name).exists() for name in OUTPUTS):
        raise ValueError("Output contains unrecognized files; choose a fresh --output-dir.")
    manifest = json.loads((ROOT / "extension/manifest.json").read_text())
    archive_name = f"cardbattlelab-enhanced-{manifest['version']}.zip"
    with tempfile.TemporaryDirectory(prefix=".build-", dir=output) as staging:
        stage = Path(staging)
        extension = stage / "extension"
        (extension / "settings").mkdir(parents=True)
        shutil.copy2(ROOT / "extension/manifest.json", extension / "manifest.json")
        shutil.copytree(ROOT / "extension/icons", extension / "icons")
        for name in SETTINGS_FILES:
            shutil.copyfile(SETTINGS_DIR / name, extension / "settings" / name)
        shutil.copyfile(OVERLAY_DIR / "features.js", extension / "settings/features.js")
        bundle = overlay_bundle()
        (extension / "overlay.js").write_text(bundle, encoding="utf-8")
        (stage / "android-assets/overlay").mkdir(parents=True)
        (stage / "android-assets/overlay/overlay.js").write_text(bundle, encoding="utf-8")
        # Android and Chrome use the same site icon, with no duplicate source PNG.
        android_icons = stage / "android-res/drawable-nodpi"
        android_icons.mkdir(parents=True)
        shutil.copyfile(ROOT / "extension/icons/cardbattlelab.png", android_icons / "cardbattlelab.png")
        with zipfile.ZipFile(stage / archive_name, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for file in sorted(extension.rglob("*")):
                if file.is_file():
                    archive.write(file, file.relative_to(extension).as_posix())
        # Everything is ready before the last good build is replaced.
        for name in OUTPUTS:
            target = output / name
            if target.is_symlink():
                raise ValueError(f"Refusing symlink output: {target}")
            if target.exists():
                shutil.rmtree(target)
            shutil.move(str(stage / name), target)
        for old in output.glob("cardbattlelab-enhanced-*.zip"):
            old.unlink()
        shutil.move(str(stage / archive_name), output / archive_name)
        marker.touch()
    print(f"Chrome: {output / 'extension'}")
    print(f"ZIP: {output / archive_name}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", default=str(ROOT / "build"), help="Generated output directory")
    args = parser.parse_args()
    try:
        package(Path(args.output_dir).expanduser())
    except (ValueError, OSError) as error:
        print(f"Build failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
